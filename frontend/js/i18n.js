// ── Language Engine ─────────────────────────────────────────
window.currentLang = localStorage.getItem('finpulse_lang') || 'en';

window.t = function(key, vars) {
  let str = (TRANSLATIONS[currentLang] || TRANSLATIONS.en)[key] || key;
  if (vars) Object.entries(vars).forEach(([k,v]) => { str = str.replace(`{${k}}`, v); });
  return str;
};

window.setLang = function(lang) {
  currentLang = lang;
  localStorage.setItem('finpulse_lang', lang);
  applyTranslations();
};

window.applyTranslations = function() {
  // nav links
  document.querySelectorAll('.nav-link[data-section]').forEach(el => {
    const sec = el.dataset.section;
    const span = el.querySelector('span');
    if (span) span.textContent = t('nav_' + sec);
  });
  document.querySelector('.user-name').textContent = t('nav_user');

  // active page title/subtitle
  const activeLink = document.querySelector('.nav-link.active');
  if (activeLink) {
    const sec = activeLink.dataset.section;
    document.getElementById('pageTitle').textContent = t('nav_' + sec);
    document.getElementById('pageSubtitle').textContent = t('sub_' + sec);
  }

  // static data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const attr = el.dataset.i18nAttr;
    if (attr) el.setAttribute(attr, t(key));
    else el.textContent = t(key);
  });

  // lang switcher active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
};
